import Foundation

func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    if !condition() { fputs("FAIL: \(message)\n", stderr); exit(1) }
}
let a = URL(fileURLWithPath: "/vault/A.md")
let b = URL(fileURLWithPath: "/vault/B.md")
let c = URL(fileURLWithPath: "/vault/C.md")
let d = URL(fileURLWithPath: "/vault/D.md")
var history = CardHistory()
check(history.current == nil && history.backTarget == nil && history.forwardTarget == nil, "empty history")
history.visit(URL(string: "https://example.com")!)
check(history.current == nil, "external URLs are not recorded")
history.visit(a)
check(history.current == a && history.backTarget == nil, "first card")
history.visit(URL(fileURLWithPath: "/vault/dir/../A.md"))
check(history.current == a && history.backTarget == nil, "same standardized path is not duplicated")
history.visit(b)
history.visit(c)
check(history.current == c && history.backTarget == b && history.forwardTarget == nil, "new visits append")
// Merely reading the target represents a navigation that was canceled: no commit.
let canceledTarget = history.backTarget
check(canceledTarget == b && history.current == c && history.forwardTarget == nil, "cancel leaves history unchanged")
check(!history.commitBack(to: a) && history.current == c, "stale non-adjacent back target rejected")
check(history.commitBack(to: b) && history.current == b && history.backTarget == a && history.forwardTarget == c, "back")
check(history.commitForward(to: c) && history.current == c && history.backTarget == b, "forward")
check(history.commitBack(to: b), "back before branching history")
history.visit(d)
check(history.current == d && history.backTarget == b && history.forwardTarget == nil, "new visit clears forward history")
check(!history.commitForward(to: c) && history.current == d, "old forward target rejected")
check(history.commitBack(to: b), "return to earlier card")
history.visit(b)
check(history.forwardTarget == d, "revisiting current card preserves forward history")
check(history.commitBack(to: b) && history.current == b && history.forwardTarget == d, "return from unsaved draft is a no-op")
check(history.commitBack(to: a) && history.backTarget == nil && history.forwardTarget == b, "first history entry")
check(!history.commitBack(to: d) && history.current == a, "cannot move past beginning")
var draftHistory = CardHistory()
draftHistory.visit(a)
draftHistory.detach()
check(draftHistory.detached && draftHistory.backTarget == a && draftHistory.forwardTarget == nil, "back from unsaved draft returns to last card")
check(!draftHistory.commitForward(to: a) && draftHistory.detached, "detached draft cannot go forward")
let draftTarget = draftHistory.backTarget!
check(draftHistory.detached && draftHistory.backTarget == draftTarget, "cancel leaves draft detached")
check(draftHistory.commitBack(to: draftTarget) && !draftHistory.detached && draftHistory.current == a, "discard draft and return")
draftHistory.detach()
draftHistory.saveCurrent(b)
check(!draftHistory.detached && draftHistory.backTarget == a, "saved draft becomes a visited card")
check(draftHistory.commitBack(to: a) && draftHistory.forwardTarget == b, "saved draft is available via forward")
draftHistory.detach()
let saveSameTarget = draftHistory.backTarget!
draftHistory.saveCurrent(a)
check(!draftHistory.detached && draftHistory.forwardTarget == b, "save to the current URL preserves forward history")
check(draftHistory.commitBack(to: saveSameTarget) && draftHistory.current == a && draftHistory.forwardTarget == b, "same-URL save and return do not duplicate history")
var emptyDraft = CardHistory()
emptyDraft.detach()
check(emptyDraft.backTarget == nil && emptyDraft.forwardTarget == nil, "first unsaved draft has no history")
var saveAsBack = CardHistory()
saveAsBack.visit(a); saveAsBack.visit(b)
let priorBack = saveAsBack.backTarget!
saveAsBack.saveCurrent(c)
check(saveAsBack.current == c && saveAsBack.backTarget == a, "save as replaces the tracked current entry")
check(saveAsBack.commitBack(to: priorBack) && saveAsBack.forwardTarget == c, "save as while going back preserves navigation")
var saveAsForward = CardHistory()
saveAsForward.visit(a); saveAsForward.visit(b)
check(saveAsForward.commitBack(to: a), "prepare for forward")
let priorForward = saveAsForward.forwardTarget!
saveAsForward.saveCurrent(c)
check(saveAsForward.current == c && saveAsForward.forwardTarget == b, "save as preserves forward history")
check(saveAsForward.commitForward(to: priorForward) && saveAsForward.backTarget == c, "save as while going forward preserves navigation")
var failedAfterSave = CardHistory()
failedAfterSave.visit(a); failedAfterSave.visit(b)
failedAfterSave.saveCurrent(c)
check(failedAfterSave.current == c && failedAfterSave.backTarget == a, "failed navigation keeps completed save as current")
var duplicateOnSave = CardHistory()
duplicateOnSave.visit(a); duplicateOnSave.visit(b); duplicateOnSave.saveCurrent(a)
check(duplicateOnSave.current == a && duplicateOnSave.backTarget == nil, "save as an adjacent entry does not leave duplicate steps")
var renamedBack = CardHistory()
renamedBack.visit(a); renamedBack.visit(b); renamedBack.visit(c)
renamedBack.rename(b, to: d)
check(renamedBack.backTarget == d && renamedBack.commitBack(to: d) && renamedBack.forwardTarget == c, "rename updates previous visit")
renamedBack.rename(c, to: b)
check(renamedBack.forwardTarget == b && renamedBack.commitForward(to: b), "rename updates forward visit")
var renamedDetached = CardHistory()
renamedDetached.visit(a); renamedDetached.visit(b); renamedDetached.detach(); renamedDetached.rename(b, to: d)
check(renamedDetached.detached && renamedDetached.backTarget == d && renamedDetached.commitBack(to: d), "rename keeps detached draft and its return destination")
var renamedDuplicate = CardHistory()
renamedDuplicate.visit(a); renamedDuplicate.visit(b); renamedDuplicate.visit(c); renamedDuplicate.rename(b, to: a)
check(renamedDuplicate.backTarget == a && renamedDuplicate.commitBack(to: a) && renamedDuplicate.backTarget == nil, "rename collapses adjacent duplicate visits")
var removedBack = CardHistory()
removedBack.visit(a); removedBack.visit(b); removedBack.visit(c); removedBack.remove(b)
check(removedBack.backTarget == a && removedBack.commitBack(to: a) && removedBack.forwardTarget == c, "trash skips an earlier visit")
var removedForward = CardHistory()
removedForward.visit(a); removedForward.visit(b); removedForward.visit(c)
check(removedForward.commitBack(to: b), "prepare forward removal")
removedForward.remove(c)
check(removedForward.current == b && removedForward.forwardTarget == nil && removedForward.backTarget == a, "trash removes forward destination")
var removedDetached = CardHistory()
removedDetached.visit(a); removedDetached.visit(b); removedDetached.detach(); removedDetached.remove(b)
check(removedDetached.detached && removedDetached.backTarget == a && removedDetached.commitBack(to: a), "trash of most recent visit preserves detached draft and returns to previous")
var removedCurrent = CardHistory()
removedCurrent.visit(a); removedCurrent.visit(b); check(removedCurrent.commitBack(to: a), "prepare earliest removal")
removedCurrent.remove(a)
check(removedCurrent.current == b && removedCurrent.backTarget == nil && removedCurrent.forwardTarget == nil, "trash of earliest visit selects surviving next visit")
removedCurrent.remove(b)
check(removedCurrent.current == nil && removedCurrent.backTarget == nil && removedCurrent.forwardTarget == nil, "trash of final visit empties history")
var removedDuplicate = CardHistory()
removedDuplicate.visit(a); removedDuplicate.visit(b); removedDuplicate.visit(a); removedDuplicate.remove(b)
check(removedDuplicate.current == a && removedDuplicate.backTarget == nil, "trash collapses adjacent duplicates")
print("History navigation, cancellation, duplicate paths, and forward-branch behavior passed")
